-- -----------------------------------------------------------
-- 5.4 Masking de PII — nombre, RUC, email
-- (Dynamic Data Masking requiere edición Enterprise)
-- -----------------------------------------------------------
USE ROLE SYSADMIN;   -- o ACCOUNTADMIN si SYSADMIN no tiene APPLY MASKING POLICY
USE SCHEMA DWH_DEMO.GOVERNANCE;

CREATE OR REPLACE MASKING POLICY MP_PII_STRING AS (val VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('R_DATA_ANALYST','R_DATA_ENGINEER','ACCOUNTADMIN','SYSADMIN')
            THEN val
        ELSE '***PROTEGIDO***'
    END;

CREATE OR REPLACE MASKING POLICY MP_PII_EMAIL AS (val VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('R_DATA_ANALYST','R_DATA_ENGINEER','ACCOUNTADMIN','SYSADMIN')
            THEN val
        ELSE REGEXP_REPLACE(val, '^[^@]+', '*****')   -- deja el dominio visible
    END;

ALTER TABLE DWH_DEMO.CURATED.DIM_CUSTOMER MODIFY COLUMN CUSTOMER_NAME SET MASKING POLICY MP_PII_STRING;
ALTER TABLE DWH_DEMO.CURATED.DIM_CUSTOMER MODIFY COLUMN TAX_ID        SET MASKING POLICY MP_PII_STRING;
ALTER TABLE DWH_DEMO.CURATED.DIM_CUSTOMER MODIFY COLUMN EMAIL         SET MASKING POLICY MP_PII_EMAIL;

