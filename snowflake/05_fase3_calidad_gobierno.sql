-- Cuarentena: los registros que fallan NO se descartan en silencio
CREATE OR REPLACE TABLE DQ_QUARANTINE (
    QUARANTINE_ID  NUMBER IDENTITY,
    RULE_ID        NUMBER,
    SOURCE_TABLE   VARCHAR,
    RECORD_KEY     VARCHAR,
    RECORD_PAYLOAD VARIANT,       -- el registro completo, para corregir en la fuente
    DETECTED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    STATUS         VARCHAR DEFAULT 'PENDIENTE'   -- PENDIENTE / CORREGIDO / DESCARTADO
);

-- Procedimiento que corre el catálogo completo y aísla lo que falla
CREATE OR REPLACE PROCEDURE SP_RUN_DQ_CHECKS()
RETURNS VARCHAR
LANGUAGE SQL
AS
BEGIN
    -- Regla 1: fechas nulas/basura
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 1, 'STG_SALES_ORDERS', ORDER_ID || '-' || ITEM_NO, OBJECT_CONSTRUCT(*)
    FROM DWH_DEMO.STAGING.STG_SALES_ORDERS WHERE ORDER_DATE IS NULL;

    -- Regla 2: importes nulos
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 2, 'STG_SALES_ORDERS', ORDER_ID || '-' || ITEM_NO, OBJECT_CONSTRUCT(*)
    FROM DWH_DEMO.STAGING.STG_SALES_ORDERS WHERE NET_AMOUNT IS NULL;

    -- Regla 3: duplicados de clave natural
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 3, 'STG_SALES_ORDERS', ORDER_ID || '-' || ITEM_NO, OBJECT_CONSTRUCT(*)
    FROM DWH_DEMO.STAGING.STG_SALES_ORDERS
    QUALIFY COUNT(*) OVER (PARTITION BY ORDER_ID, ITEM_NO) > 1
        AND ROW_NUMBER() OVER (PARTITION BY ORDER_ID, ITEM_NO ORDER BY _LOADED_AT) > 1;

    -- Regla 4: huérfanos (cliente inexistente)
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 4, 'STG_SALES_ORDERS', s.ORDER_ID || '-' || s.ITEM_NO, OBJECT_CONSTRUCT(s.*)
    FROM DWH_DEMO.STAGING.STG_SALES_ORDERS s
    LEFT JOIN DWH_DEMO.CURATED.DIM_CUSTOMER c
      ON c.CUSTOMER_ID = s.CUSTOMER_ID AND c.IS_CURRENT
    WHERE c.CUSTOMER_ID IS NULL;

    -- Regla 5: rangos
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 5, 'STG_SALES_ORDERS', ORDER_ID || '-' || ITEM_NO, OBJECT_CONSTRUCT(*)
    FROM DWH_DEMO.STAGING.STG_SALES_ORDERS
    WHERE QUANTITY IS NOT NULL AND QUANTITY NOT BETWEEN 0 AND 100000;

    -- Regla 6: formato de RUC
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 6, 'STG_CUSTOMERS', CUSTOMER_ID, OBJECT_CONSTRUCT(*)
    FROM DWH_DEMO.STAGING.STG_CUSTOMERS
    WHERE TAX_ID IS NULL OR NOT TAX_ID REGEXP '^[0-9]{11}$';

    -- Regla 7: consistencia cruzada factura vs orden
    INSERT INTO DQ_QUARANTINE (RULE_ID, SOURCE_TABLE, RECORD_KEY, RECORD_PAYLOAD)
    SELECT 7, 'STG_BILLING', b.BILLING_ID || '-' || b.ITEM_NO, OBJECT_CONSTRUCT(b.*)
    FROM DWH_DEMO.STAGING.STG_BILLING b
    JOIN DWH_DEMO.STAGING.STG_SALES_ORDERS s
      ON s.ORDER_ID = b.REF_ORDER_ID AND s.ITEM_NO = b.ITEM_NO
    WHERE b.QUANTITY > s.QUANTITY * 1.05;    -- tolerancia 5%

    RETURN 'DQ checks ejecutados. Ver GOVERNANCE.DQ_QUARANTINE';
END;

CALL SP_RUN_DQ_CHECKS();

-- Vista resumen para mostrar en la demo: "la calidad deja de ser un acto de fe"
CREATE OR REPLACE VIEW V_DQ_DASHBOARD AS
SELECT r.RULE_ID, r.RULE_NAME, r.RULE_TYPE, r.SEVERITY,
       COUNT(q.QUARANTINE_ID) AS REGISTROS_AFECTADOS,
       MAX(q.DETECTED_AT)     AS ULTIMA_DETECCION
FROM DQ_RULES r
LEFT JOIN DQ_QUARANTINE q ON q.RULE_ID = r.RULE_ID
GROUP BY 1,2,3,4
ORDER BY r.RULE_ID;

